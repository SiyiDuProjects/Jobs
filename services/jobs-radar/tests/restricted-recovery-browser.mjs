import {createRequire} from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const [origin, work, modulePath, executablePath]=process.argv.slice(2);
const {chromium}=createRequire(import.meta.url)(modulePath);
const browser=await chromium.launch({executablePath,headless:true,args:['--host-resolver-rules=MAP * ~NOTFOUND, EXCLUDE 127.0.0.1']});
const evidence={checks:[],pageErrors:[],network:'Only the isolated loopback ASGI server; fresh context without extensions'};
try {
  const context=await browser.newContext({viewport:{width:1280,height:900}});
  await context.route('**/*',route=>new URL(route.request().url()).origin===origin?route.continue():route.abort());
  await context.addCookies([{name:'radar_browser',value:'browser-synthetic-cookie',url:origin,httpOnly:true,sameSite:'Lax'}]);
  const page=await context.newPage();
  page.on('pageerror',error=>evidence.pageErrors.push(error.message));
  await page.goto(origin,{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'Profile',exact:true}).waitFor();
  assert.match(await page.getByRole('status').first().textContent(),/受限恢复模式/);
  evidence.checks.push('Existing packaged Profile page loaded with visible application pause');
  await page.getByRole('button',{name:'Edit Personal Details',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('First Name',{exact:true}).fill('RecoveryBrowser');
  const saved=page.waitForResponse(response=>response.url().includes('/api/manage/profiles/')&&response.request().method()==='PUT');
  await dialog.getByRole('button',{name:'Save',exact:true}).click();
  assert.equal((await saved).status(),200);
  await dialog.waitFor({state:'hidden'});
  await page.reload({waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Edit Personal Details',exact:true}).click();
  assert.equal(await page.getByRole('dialog').getByLabel('First Name',{exact:true}).inputValue(),'RecoveryBrowser');
  await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click();
  evidence.checks.push('Profile edit persisted across an actual browser reload');
  await page.getByRole('button',{name:'Manage',exact:true}).click();
  await page.getByRole('menuitem',{name:'Add',exact:true}).click();
  const answerDialog=page.getByRole('dialog');
  for (const keyword of ['synthetic','recovery','answer']) {
    await answerDialog.getByRole('textbox',{name:'Add Keywords',exact:true}).fill(keyword);
    await answerDialog.getByRole('button',{name:'Add',exact:true}).click();
  }
  await answerDialog.getByLabel('Response',{exact:true}).fill('Recovery response saved');
  const answerSaved=page.waitForResponse(response=>response.url().endsWith('/api/manage/state')&&response.request().method()==='POST');
  await answerDialog.getByRole('button',{name:'Save',exact:true}).click();
  assert.equal((await answerSaved).status(),200);
  await answerDialog.waitFor({state:'hidden'});
  await page.reload({waitUntil:'networkidle'});
  await page.getByText('Recovery response saved',{exact:true}).waitFor();
  evidence.checks.push('Saved Profile response normalized and persisted through the actual existing editor');
  await page.getByRole('button',{name:'设置',exact:true}).click();
  await page.getByRole('heading',{name:'Settings',exact:true}).waitFor();
  await page.getByLabel('Daily Application Goal',{exact:true}).fill('17');
  const settingsSaved=page.waitForResponse(response=>response.url().endsWith('/api/manage/state')&&response.request().method()==='POST');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  assert.equal((await settingsSaved).status(),200);
  await page.reload({waitUntil:'networkidle'});
  await page.getByRole('button',{name:'设置',exact:true}).click();
  assert.equal(await page.getByLabel('Daily Application Goal',{exact:true}).inputValue(),'17');
  evidence.checks.push('Settings edit persisted across reload using the existing settings page');
  await page.screenshot({path:path.join(work,'settings.png'),fullPage:true});
  await page.getByRole('button',{name:'个人资料',exact:true}).click();
  await page.getByRole('heading',{name:'Profile',exact:true}).waitFor();
  await page.screenshot({path:path.join(work,'profile.png'),fullPage:true});
  assert.deepEqual(evidence.pageErrors,[]);
  await fs.writeFile(path.join(work,'browser-result.json'),JSON.stringify(evidence,null,2));
  console.log(JSON.stringify(evidence));
} finally {await browser.close();}
