#!/usr/bin/env python3
"""Render the ATS index from redacted run metadata and explicit case annotations.

Diagnostics establish occurrence/coverage, not whether a repair is verified.
Existing human acceptance statements survive every regeneration unchanged.
No event text, values, options, URLs or Profile data enter the output.
"""
import argparse
from collections import Counter
import json
from pathlib import Path


def import_annotations(markdown):
    sections=[]; current=None; intro=[]
    for line in markdown.splitlines():
        if line.startswith('## '):
            current={'ats':line[3:], 'rows':[]}; sections.append(current)
        elif current is None:
            intro.append(line)
        elif line.startswith('| P'):
            parts=line.strip().strip('|').split('|')
            if len(parts)!=3: raise ValueError('Case row must have three columns')
            priority, summary, evidence=[part.strip() for part in parts]
            if priority not in {'P0','P1','P2'}: raise ValueError('Invalid priority')
            current['rows'].append({'priority':priority,'summary':summary,'evidence':evidence})
        elif line.strip() and not line.startswith('|'):
            current.setdefault('notes',[]).append(line)
    return {'version':1,'intro':'\n'.join(intro).strip(),'sections':sections}


def render(annotations, runs):
    if annotations.get('version')!=1 or not isinstance(runs,list):
        raise ValueError('Expected v1 annotations and an array of redacted runs')
    unique={}
    for run in runs:
        if not isinstance(run,dict) or not isinstance(run.get('id'),str):
            raise ValueError('Run id missing')
        unique[run['id']]=run
    counts=Counter(str(run.get('ats','unknown')) for run in unique.values())
    truncated=sum(run.get('truncated') is True for run in unique.values())
    parts=[annotations['intro'],
           f'<!-- Generated by scripts/generate-ats-index.py. Edit case annotations, then regenerate. -->\n\n本次诊断输入：{len(unique)} 次运行；{truncated} 份截断。仅统计所提供的快照，不代表投递成功数或完整历史。',
           '诊断覆盖：'+ '、'.join(f'{ats} {count}' for ats,count in sorted(counts.items()))+'。']
    for section in annotations['sections']:
        parts.append('## '+section['ats'])
        table = ['| 级别 | 问题与状态 | 证据 |', '| --- | --- | --- |']
        for row in section['rows']:
            if row['priority'] not in {'P0','P1','P2'}: raise ValueError('Invalid priority')
            cells=[row[key] for key in ['priority','summary','evidence']]
            if any(not isinstance(cell,str) or '\n' in cell or '|' in cell for cell in cells):
                raise ValueError('Invalid case annotation')
            table.append('| '+' | '.join(cells)+' |')
        parts.append('\n'.join(table))
        parts.extend(section.get('notes',[]))
    return '\n\n'.join(parts)+'\n'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--import-markdown',type=Path)
    parser.add_argument('--annotations',type=Path,required=True)
    parser.add_argument('--diagnostics',type=Path)
    parser.add_argument('--output',type=Path)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    if args.import_markdown:
        if args.annotations.exists(): parser.error('Annotation file exists; refusing to overwrite accepted statuses')
        args.annotations.write_text(json.dumps(import_annotations(args.import_markdown.read_text()),ensure_ascii=False,indent=2)+'\n')
        return
    if not args.diagnostics or not args.output: parser.error('Diagnostics and output are required')
    result=render(json.loads(args.annotations.read_text()),json.loads(args.diagnostics.read_text()))
    if args.check:
        if not args.output.exists() or args.output.read_text()!=result: raise SystemExit('ATS index is stale')
    else: args.output.write_text(result)

if __name__=='__main__': main()
